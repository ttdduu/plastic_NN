import torch
import torch.nn as nn
from torch.nn.parameter import Parameter
from math import prod
import numpy as np
import time

def conv2d_output_size(input_size, out_channels, padding, kernel_size, stride, dilation):
    """According to https://pytorch.org/docs/stable/generated/torch.nn.Conv2d.html
    """
    if isinstance(dilation, int):
        dilation = (dilation, ) * 2
    if isinstance(padding, int):
        padding = (padding, ) * 2
    if isinstance(kernel_size, int):
        kernel_size = (kernel_size, ) * 2
    if isinstance(stride, int):
        stride = (stride, ) * 2

    output_size = (
            np.floor((input_size[0] + 2 * padding[0] - dilation[0] * (kernel_size[0] - 1) - 1) /
                stride[0] + 1).astype(int),
            np.floor((input_size[1] + 2 * padding[1] - dilation[1] * (kernel_size[1] - 1) - 1) /
                stride[1] + 1).astype(int)
            )
    return output_size

class LocalyConnected2d(nn.Module):
     # authors: Ismail Khalfaoui & Timothee Masquelier
    _first_batch_done = False
    _forward_count = 0
    # Class-level block counters that persist across instances
    # _stage_block_counters = {1: 0, 2: 0, 3: 0, 4: 0}
    _stage_block_counters = {1: 0, 2: 0, 3: 0,4:0}
    #_stage_block_counters = {1: 0, 2: 0, 3: 0}

    def __init__(self, input_size, in_channels, out_channels, kernel_size, stride=1, padding=0, dilation=1, groups=1, trainable_bias=False, pretrained_weight=None, pretrained_bias=None, weight_name=None, stage=None):
        super().__init__()

        self.stride = stride
        self.padding = padding
        self.dilation = dilation
        self.groups = groups
        self.weight_name = weight_name  # Store the weight name

        self.input_size = input_size
        self.in_channels = in_channels
        self.out_channels = out_channels
        self.kernel_size = kernel_size
        self.trainable_bias = trainable_bias

        # Determine stage: prefer explicit parameter, fall back to channel heuristic
        if stage is not None:
            self.stage = stage
        elif out_channels == 16: self.stage = 1
        elif out_channels == 32: self.stage = 2
        elif out_channels == 64: self.stage = 3
        elif out_channels == 128: self.stage = 4
        else: self.stage = 0

        # Ensure counter key exists, then increment
        if self.stage not in LocalyConnected2d._stage_block_counters:
            LocalyConnected2d._stage_block_counters[self.stage] = 0
        LocalyConnected2d._stage_block_counters[self.stage] += 1
        self.block_num = LocalyConnected2d._stage_block_counters[self.stage]

        output_size = conv2d_output_size(input_size=input_size, out_channels=out_channels, padding=padding, kernel_size=kernel_size, stride=stride, dilation=dilation)
        self.output_size = output_size

        # Initialize weights
        if pretrained_weight is not None:
            weights = pretrained_weight.unsqueeze(0)  # Add spatial dimension
            weights = weights.expand(*output_size, -1, -1, -1, -1).clone()
            weights = weights.view(prod(self.output_size), out_channels, in_channels // groups * kernel_size * kernel_size)
            weights = weights.view(prod(self.output_size), groups, out_channels//groups, in_channels//groups*kernel_size*kernel_size)
            weights = weights.permute(1, 0, 3, 2)
            self.weights = Parameter(weights)
        else:
            weights = torch.empty(groups, prod(output_size), in_channels//groups*kernel_size*kernel_size, out_channels//groups)
            nn.init.kaiming_normal_(weights.view(groups, -1), mode='fan_in', nonlinearity='linear')
            self.weights = Parameter(weights)

        # Initialize bias - similar expansion as weights
        if pretrained_bias is not None:
            # Expand bias to all output positions
            # bias_tensor = pretrained_bias.unsqueeze(0)  # [1, out_channels]
            # bias_tensor = bias_tensor.expand(prod(self.output_size), -1)  # [H*W, out_channels]
            # bias_tensor = torch.zeros(prod(self.output_size), out_channels)
            # bias_tensor = None
            # for lc biases
            print(pretrained_bias.shape)
            bias_tensor = pretrained_bias.view(1, -1).expand(prod(self.output_size), -1).contiguous()
            print(bias_tensor.shape)

        else:
            # bias_tensor = torch.zeros(prod(self.output_size), out_channels)
            # bias_tensor = torch.zeros(prod(self.output_size), out_channels, dtype=self.weights.dtype, device=self.weights.device)
            bias_tensor = None
            # print("Mean of bias_tensor:", bias_tensor.mean().item())
        # trainable_bias=True

        if trainable_bias:
            self.bias = Parameter(bias_tensor)
        else:
            # self.register_buffer('bias', bias_tensor, persistent=True)
            self.bias = None

        # unfold extracts patches that would normally be convolved with shared weights
        # OK
        self.unfold = nn.Unfold(kernel_size=kernel_size, dilation=dilation, padding=padding, stride=stride)

    def forward(self, x):
        N = x.size(0)

        patches = self.unfold(x)
        patches = patches.view(N, self.groups, -1, patches.size(-1))
        # reshape for groups
        patches = patches.permute(1,3,0,2)
        out = patches.matmul(self.weights)
        out = out.permute(1,2,0,3)
        out = out.reshape(prod(self.output_size),-1,self.out_channels)
        out = out.permute(1,2,0).view(-1, self.out_channels, *self.output_size)
        if self.bias is not None:
            out = out + self.bias.unsqueeze(1)


        LocalyConnected2d._forward_count += 1
        if LocalyConnected2d._forward_count >= 12:  # Total number of LC layers
            LocalyConnected2d._first_batch_done = True
            LocalyConnected2d._forward_count = 0
            # No need to reset block counters as they're now assigned at initialization

        return out
