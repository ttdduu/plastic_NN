def _alternating_ring_mask(
    H: int,
    W: int,
    radius_pct: float,
    ring_width_pct: float,
    center_visible: bool = True,
    sharpness: float = 6.0,
    soft: bool = True,
    shape: str = "annular",
    dtype=torch.float32,
) -> torch.Tensor:
    """Return a (H, W) mask in [0, 1] that splits a centred region of
    `radius_pct` % of W into concentric bands of width `ring_width_pct` % of W,
    alternating visible (≈1) and occluded (≈0). Outside the region: visible.

    shape="annular"     → circular rings   (Euclidean distance from centre).
    shape="rectangular" → concentric SQUARE frames (Chebyshev / L∞ distance):
                          same band width, alternation, extent and phase, just
                          square instead of round.

    Width should be ≤ the lateral's per-T reach in input px so the network can
    learn to bridge occluded bands from neighbouring visible ones.

    soft=True uses sigmoid band edges (continuous, gradient-friendly);
    soft=False uses hard step edges (cheaper, fine for augmentation).
    """
    y, x = torch.meshgrid(
        torch.arange(H, dtype=dtype),
        torch.arange(W, dtype=dtype),
        indexing="ij",
    )
    cy, cx = H // 2, W // 2
    if shape == "rectangular":
        # Chebyshev (L∞) distance → concentric SQUARE frames instead of circles.
        # Everything downstream (R, w, ring_idx, alternation, soft bands) is identical.
        d = torch.maximum((x - cx).abs(), (y - cy).abs())
    else:
        d = torch.sqrt((x - cx) ** 2 + (y - cy) ** 2)
    R = radius_pct / 100.0 * W
    w = max(1e-6, ring_width_pct / 100.0 * W)

    if not soft:
        ring_idx = (d / w).floor().long()
        # center_visible=True → occluded on odd rings; else on even rings
        is_occluded = (ring_idx % 2 == 1) if center_visible else (ring_idx % 2 == 0)
        is_inside = d <= R
        mask = torch.ones(H, W, dtype=dtype)
        mask[is_occluded & is_inside] = 0.0
        return mask

    # Soft alternating: sum of sigmoid bands. Each occluded ring [s, s+w] has
    # indicator = sigmoid(sharp·(d − s)) − sigmoid(sharp·(d − (s+w))).
    n_rings = int(R / w)
    occluded_total = torch.zeros(H, W, dtype=dtype)
    start_indices = range(1, n_rings + 1, 2) if center_visible else range(0, n_rings + 1, 2)
    for i in start_indices:
        s_in = i * w
        s_out = min((i + 1) * w, R)
        if s_out <= s_in:
            continue
        band = torch.sigmoid(sharpness * (d - s_in)) - torch.sigmoid(sharpness * (d - s_out))
        occluded_total = occluded_total + band
    occluded_total = occluded_total.clamp(0.0, 1.0)
    outside = (d > R).to(dtype)
    occluded_total = occluded_total * (1.0 - outside)
    return 1.0 - occluded_total


def apply_ring_occlusion(
    img: torch.Tensor,
    radius_pct: float,
    ring_width_pct: float,
    *,
    center_visible: bool = True,
    sharpness: float = 6.0,
    soft: bool = True,
    shape: str = "annular",
    mask_shift: Tuple[int, int] = (0, 0),
) -> Tuple[torch.Tensor, torch.Tensor]:
    """Occlude `img` (..., H, W) with an alternating ring mask; return
    (occluded_img, mask).

    The mask (H, W; visible≈1, occluded≈0) is generated by
    `_alternating_ring_mask` and broadcast over img's leading dims, so this works
    for a single image (C, H, W) or a batch (B, C, H, W). `mask_shift` = (dy, dx)
    rolls the whole mask — used by the recon trainer to jitter hole positions per
    batch. Single source of truth for "apply a ring occlusion", shared by
    ScotomaDataset.__getitem__ and the reconstruction-loss trainer.
    """
    H, W = img.shape[-2], img.shape[-1]
    mask = _alternating_ring_mask(
        H, W,
        radius_pct=radius_pct, ring_width_pct=ring_width_pct,
        center_visible=center_visible, sharpness=sharpness, soft=soft, shape=shape,
        dtype=img.dtype,
    )
    if mask_shift != (0, 0):
        mask = torch.roll(mask, shifts=mask_shift, dims=(0, 1))
    mask = mask.to(img.device)
    return img * mask, mask


class ScotomaDataset(torch.utils.data.Dataset):
    def __init__(self, base_dataset, config, is_training=True):
        print("Initializing ScotomaDataset from src/data/scotoma_dataset.py")
        self.base_dataset = base_dataset
        self.config = config
        self.is_training = is_training
        self.logpolar = None
        self.fisheye = None
        # Always normalize at the end so that any scotoma/logpolar/fisheye are applied before normalization
        # self.final_normalize = transforms.Normalize(mean=config.mean, std=config.std)
        self.final_normalize = transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])

        # Pass through the classes attribute from base_dataset
        self.classes = base_dataset.classes

        # Initialize transforms - always create it if needed for either phase
        self.scotoma = ScotomaApplier(config) if (
            config.scotoma_apply or config.scotoma_apply_val
        ) else None

        if config.logpolar_apply:
            logpolar_rows = getattr(config, 'logpolar_rows', 224)
            logpolar_cols = getattr(config, 'logpolar_cols', 224)
            self.logpolar = LogPolarTransform(N_rows=logpolar_rows, N_cols=logpolar_cols)
            print(f"logpolar initialized: {self.logpolar is not None}")
        if config.fisheye_apply:
            C = getattr(config,'fisheye_C',1)
            K = getattr(config,'fisheye_K')
            rfov = getattr(config,'fisheye_rfov')
            self.fisheye = FisheyeTransform(C=C, K=K, rfov=rfov)
            print(f"fisheye initialized: {self.fisheye is not None}")
        if config.rsl_apply:
            fov = getattr(config, 'rsl_fov')
            out_size = getattr(config, 'rsl_out_size', 256)
            rsl_type = getattr(config, 'rsl_type', 1)
            apply_mask = getattr(config, 'rsl_apply_mask', True)
            self.rsl = RSLTransform(fov=fov, out_size=out_size, type=rsl_type, apply_mask=apply_mask)
            print(f"rsl initialized: {self.rsl is not None}")


    def _radius_grid(self):
        """Discrete radius grid as a list. Prefer an explicit `scotoma_radius_grid`
        (allows non-uniform sets like [0, 20, 26, 32]); else build from
        min/max/step. radius 0 → a fully-visible 'normal' sample (still fisheye'd)."""
        grid = getattr(self.config, "scotoma_radius_grid", None)
        if grid:
            return [float(r) for r in grid]
        r_min = float(getattr(self.config, "scotoma_radius_min", 20))
        r_max = float(getattr(self.config, "scotoma_radius_max", 32))
        r_step = float(getattr(self.config, "scotoma_radius_step", 6))
        if r_step > 0 and r_max > r_min:
            n = int((r_max - r_min) / r_step) + 1
            return [r_min + r_step * i for i in range(n)]
        return [r_min]

    def _shape_list(self):
        """Enabled band shapes — each used SEPARATELY per sample (NOT overlaid).
        Both on → samples come in two flavours (circular and square); the dataset
        covers both as another axis, like the radius grid."""
        shapes = []
        if bool(getattr(self.config, "scotoma_annular_circular", True)):
            shapes.append("annular")
        if bool(getattr(self.config, "scotoma_annular_rectangular", False)):
            shapes.append("rectangular")
        return shapes or ["annular"]

    def _combo_grid(self):
        """The (radius, shape) combos the multiply mode expands over — the cross
        product of the radius grid and the enabled shapes. radius 0 is fully
        visible regardless of shape, so it contributes a SINGLE 'normal' combo
        (no per-shape duplication). E.g. radii [0,20,26,32] × {annular,square} →
        1 normal + 3 annular + 3 square = 7 versions per image."""
        shapes = self._shape_list()
        combos = []
        for r in self._radius_grid():
            if float(r) == 0.0:
                combos.append((r, shapes[0]))          # normal — shape irrelevant
            else:
                combos.extend((r, s) for s in shapes)
        return combos

    def _multiply(self) -> bool:
        """Option A: expand the TRAINING set so every image is seen once per
        (radius, shape) combo within a single epoch. Needs scotoma_radius_multiply
        + annular bands + a >1-combo grid. Off → option B (a random radius and
        random shape per access)."""
        return (
            self.is_training
            and bool(getattr(self.config, "scotoma_apply", False))
            and bool(getattr(self.config, "scotoma_annular", False))
            and bool(getattr(self.config, "scotoma_radius_multiply", False))
            and len(self._combo_grid()) > 1
        )

    def __getitem__(self, index):
        # Option A (multiply): map the expanded index → (image, forced (radius,
        # shape)) so every image appears once per (radius, shape) combo per epoch.
        # The ring phase stays randomized per access.
        forced_radius, forced_shape = None, None
        if self._multiply():
            grid = self._combo_grid()
            forced_radius, forced_shape = grid[index % len(grid)]
            index = index // len(grid)

        img, label = self.base_dataset[index]

        # Normalize FIRST
        img = self.final_normalize(img)

        # Apply scotoma AFTER normalization so scotoma region is exactly zero.
        # In reconstruction-loss mode the dataset yields CLEAN images — the recon
        # trainer fabricates the occluded copies itself (and needs the clean image
        # for the target), so skip ALL dataset masking here regardless of the
        # scotoma_* flags. (Removes the need for the scotoma_radius_grid=[0] trick.)
        recon = bool(getattr(self.config, "recon_loss_enabled", False))
        if (not recon) and self.scotoma and (
            (self.is_training and self.config.scotoma_apply) or
            (not self.is_training and self.config.scotoma_apply_val)
        ):
            # img_before_scotoma = img.clone()  # For inverse scotoma
            if forced_radius is not None:
                # Option A: radius fixed by the expanded index (deterministic —
                # every image at every grid radius once per epoch).
                radius = forced_radius
            elif self.is_training and getattr(self.config, "scotoma_random_radius", False):
                # Option B: one radius drawn uniformly from the discrete grid per
                # access; dataset length unchanged, coverage accrues over epochs.
                grid = self._radius_grid()
                radius = grid[int(torch.randint(len(grid), (1,)).item())]
            else:
                radius = self.config.scotoma_radius

            # Annular scotoma (training only): splits the disk into concentric
            # rings so the network has to bridge across occluded rings via the
            # lateral. Validation always falls through to the filled-disk path
            # for measurement consistency.
            use_annular = self.is_training and bool(
                getattr(self.config, "scotoma_annular", False)
            )
            if use_annular:
                C, H, W = img.shape
                ring_w = float(getattr(self.config, "scotoma_annular_ring_width", 4))
                if bool(getattr(self.config, "scotoma_annular_center_visible_random", False)):
                    # Randomize the ring phase per sample: occluded rings sit at
                    # "radius x" (center visible) or "radius x + ring_width" (center
                    # occluded), so the network can't lock onto a fixed phase.
                    center_vis = bool(torch.randint(2, (1,)).item())
                else:
                    center_vis = bool(getattr(self.config, "scotoma_annular_center_visible", True))
                soft = bool(getattr(self.config, "scotoma_annular_soft", True))
                # ONE band shape per sample (shapes are used SEPARATELY, not
                # overlaid): the multiply combo's shape if set, else a random
                # enabled shape per access (covers both over epochs), else the
                # single enabled shape.
                if forced_shape is not None:
                    shape = forced_shape
                else:
                    shape_list = self._shape_list()
                    shape = (shape_list[int(torch.randint(len(shape_list), (1,)).item())]
                             if len(shape_list) > 1 else shape_list[0])
                # Image is normalized → multiplying by 0 inside occluded rings
                # leaves them at the normalized zero point (≈ image mean), same
                # convention as the disk path. apply_ring_occlusion is the shared
                # mask-and-apply path (also used by the recon trainer).
                img, _mask = apply_ring_occlusion(
                    img, radius, ring_w,
                    center_visible=center_vis,
                    sharpness=getattr(self.config, "scotoma_sharpness", 6.0),
                    soft=soft,
                    shape=shape,
                )
            else:
                img = self.scotoma.apply_scotoma(
                    img.unsqueeze(0),
                    method=self.config.scotoma_method,
                    strength=self.config.scotoma_strength,
                    radius=radius,
                    sharpness=self.config.scotoma_sharpness
                ).squeeze(0)
            # img = img_before_scotoma - img  # Invert: keep center, mask periphery (comment out to revert)

        # Apply log-polar after scotoma if configured
        if self.logpolar:
            img = self.logpolar(img.unsqueeze(0)).squeeze(0)
        # Recon mode: occluded views are fabricated by the consumers (the recon
        # trainer and _recon_validate), which must mask BEFORE the fisheye (same
        # order as the scotoma path above: normalize → mask → fisheye). So yield
        # the PRE-fisheye clean for BOTH splits under recon (train AND val) and let
        # the consumers do mask→fisheye via synth_occluded_views; the clean-val
        # forward warps in _validate. This lets _recon_validate reuse the SAME
        # mask path as training. Sizing stays correct: dws_mix re-applies the
        # fisheye to input_H, so a pre-fisheye val sample (256²) still builds the
        # model at the post-fisheye 156². Non-recon goes straight to the model → warp here.
        recon_train = recon
        if self.fisheye and not recon_train:
            img = self.fisheye(img.unsqueeze(0)).squeeze(0)
        # if self.rsl_apply:
            # img = self.rsl(img.unsqueeze(0)).squeeze(0)

        return img, label

    def __len__(self):
        # Option A multiplies the length so one epoch covers every
        # (image, radius, shape) combo exactly once; otherwise unchanged.
        if self._multiply():
            return len(self.base_dataset) * len(self._combo_grid())
        return len(self.base_dataset)
